import { access, copyFile, rm, writeFile } from "node:fs/promises";
import { relative, resolve, sep } from "node:path";
import { publicPackageDirectories } from "./public-packages.mjs";

const action = process.argv[2];
const root = resolve(import.meta.dirname, "..");
const packageDirectory = resolve(process.cwd());
const packagePath = relative(root, packageDirectory).split(sep).join("/");
const licensePath = resolve(packageDirectory, "LICENSE");
const markerPath = resolve(packageDirectory, ".mds-generated-license");

if (!publicPackageDirectories.includes(packagePath)) {
  throw new Error(`Refusing to manage a package license outside the public package list: ${packagePath}.`);
}

if (action === "add") {
  if (await pathExists(licensePath)) {
    throw new Error(`Refusing to overwrite an existing package license at ${licensePath}.`);
  }
  if (await pathExists(markerPath)) {
    throw new Error(`A stale generated-license marker exists at ${markerPath}. Run this script with "remove" first.`);
  }

  await writeFile(markerPath, "Generated by scripts/manage-package-license.mjs.\n", { flag: "wx" });
  try {
    await copyFile(resolve(root, "LICENSE"), licensePath);
  } catch (error) {
    await rm(markerPath, { force: true });
    throw error;
  }
} else if (action === "remove") {
  if (await pathExists(markerPath)) {
    await rm(licensePath, { force: true });
    await rm(markerPath, { force: true });
  }
} else {
  throw new Error('Expected package-license action "add" or "remove".');
}

async function pathExists(path) {
  try {
    await access(path);
    return true;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}
